export interface QuizOption {
  id: string;
  labelAr: string;
  isCorrect: boolean;
  feedbackAr: string;
}

export interface QuizQuestion {
  id: string;
  topic: 'space' | 'nutrition' | 'health_physics';
  icon: string;
  questionAr: string;
  correctIndex: number;
  options: QuizOption[];
  nasaConnectionAr: string;
  nasaBadgeAr: string;
}

interface RawQuestionInput {
  id: string;
  topic: 'space' | 'nutrition' | 'health_physics';
  icon: string;
  questionAr: string;
  correct: { labelAr: string; feedbackAr: string };
  wrongs: [
    { labelAr: string; feedbackAr: string },
    { labelAr: string; feedbackAr: string },
    { labelAr: string; feedbackAr: string }
  ];
  nasaConnectionAr: string;
  nasaBadgeAr: string;
}

const OPTION_IDS = ['a', 'b', 'c', 'd'] as const;

/**
 * Places the correct answer evenly across indices 0, 1, 2, 3 (أ، ب، ج، د)
 * so no option letter dominates the static banks.
 */
function buildBalancedBank(items: readonly RawQuestionInput[], offset: number): readonly QuizQuestion[] {
  return items.map((item, idx) => {
    const targetIndex = (idx + offset) % 4;
    const rawList: Omit<QuizOption, 'id'>[] = [
      { labelAr: item.wrongs[0].labelAr, isCorrect: false, feedbackAr: item.wrongs[0].feedbackAr },
      { labelAr: item.wrongs[1].labelAr, isCorrect: false, feedbackAr: item.wrongs[1].feedbackAr },
      { labelAr: item.wrongs[2].labelAr, isCorrect: false, feedbackAr: item.wrongs[2].feedbackAr }
    ];
    rawList.splice(targetIndex, 0, {
      labelAr: item.correct.labelAr,
      isCorrect: true,
      feedbackAr: item.correct.feedbackAr
    });

    const options: QuizOption[] = rawList.map((opt, optIdx) => ({
      id: OPTION_IDS[optIdx],
      labelAr: opt.labelAr,
      isCorrect: opt.isCorrect,
      feedbackAr: opt.feedbackAr
    }));

    return {
      id: item.id,
      topic: item.topic,
      icon: item.icon,
      questionAr: item.questionAr,
      correctIndex: targetIndex,
      options,
      nasaConnectionAr: item.nasaConnectionAr,
      nasaBadgeAr: item.nasaBadgeAr
    };
  });
}

